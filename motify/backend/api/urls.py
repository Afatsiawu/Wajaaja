"""
URL map for the Motify API.

Standard REST routes are generated by DRF's router; the auth endpoints and
the platform stats endpoint are declared explicitly.
"""
from django.urls import include, path
from rest_framework.routers import DefaultRouter

from .views import (
    BikeModelViewSet,
    CategoryViewSet,
    ChangePasswordView,
    ContactLogViewSet,
    DemoLoginView,
    FavoritesView,
    ForgotPasswordView,
    LoginView,
    LogoutView,
    MechanicViewSet,
    MeView,
    ProductViewSet,
    RegisterView,
    ReservationViewSet,
    ResetPasswordView,
    ReviewViewSet,
    ShopViewSet,
    StatsView,
    UserViewSet,
    VehicleViewSet,
)

router = DefaultRouter()
router.register("shops", ShopViewSet, basename="shop")
router.register("mechanics", MechanicViewSet, basename="mechanic")
router.register("categories", CategoryViewSet, basename="category")
router.register("bike-models", BikeModelViewSet, basename="bike-model")
router.register("products", ProductViewSet, basename="product")
router.register("reservations", ReservationViewSet, basename="reservation")
router.register("reviews", ReviewViewSet, basename="review")
router.register("contact-log", ContactLogViewSet, basename="contact-log")
router.register("users", UserViewSet, basename="user")
router.register("auth/vehicles", VehicleViewSet, basename="vehicle")

urlpatterns = [
    # authentication
    path("auth/login/", LoginView.as_view(), name="auth-login"),
    path("auth/demo-login/", DemoLoginView.as_view(), name="auth-demo-login"),
    path("auth/register/", RegisterView.as_view(), name="auth-register"),
    path("auth/logout/", LogoutView.as_view(), name="auth-logout"),
    path("auth/me/", MeView.as_view(), name="auth-me"),
    path("auth/change-password/", ChangePasswordView.as_view(), name="auth-change-password"),
    path("auth/forgot-password/", ForgotPasswordView.as_view(), name="auth-forgot-password"),
    path("auth/reset-password/", ResetPasswordView.as_view(), name="auth-reset-password"),
    path("auth/favorites/", FavoritesView.as_view(), name="auth-favorites"),
    # platform stats for the home + admin dashboards
    path("stats/", StatsView.as_view(), name="stats"),
    path("", include(router.urls)),
]
